import { jsPDF } from 'jspdf';
import { locationToText } from './apiClient';

const PAGE_WIDTH = 210;
const PAGE_HEIGHT = 297;
const MARGIN = 18;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2;

function imageAsDataUrl(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result);
    reader.onerror = () => reject(reader.error || new Error('Image could not be read'));
    reader.readAsDataURL(file);
  });
}

function imageDimensions(dataUrl) {
  return new Promise((resolve, reject) => {
    const image = new Image();
    image.onload = () => resolve({ width: image.naturalWidth, height: image.naturalHeight });
    image.onerror = () => reject(new Error('Image could not be loaded'));
    image.src = dataUrl;
  });
}

function addPageIfNeeded(doc, y, requiredHeight = 12) {
  if (y + requiredHeight <= PAGE_HEIGHT - MARGIN) return y;
  doc.addPage();
  return MARGIN;
}

function addWrappedText(doc, text, x, y, options = {}) {
  const value = String(text ?? '—');
  const fontSize = options.fontSize || 10.5;
  const lineHeight = options.lineHeight || 5.4;
  const lines = doc.splitTextToSize(value, options.width || CONTENT_WIDTH);
  doc.setFontSize(fontSize);
  doc.setTextColor(...(options.color || [25, 49, 41]));
  lines.forEach((line) => {
    y = addPageIfNeeded(doc, y, lineHeight);
    doc.text(line, x, y);
    y += lineHeight;
  });
  return y;
}

function addSection(doc, title, value, y) {
  y = addPageIfNeeded(doc, y, 16);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(23, 75, 53);
  doc.text(title.toUpperCase(), MARGIN, y);
  y += 5;
  doc.setFont('helvetica', 'normal');
  return addWrappedText(doc, value, MARGIN, y, { lineHeight: 5.5 });
}

/** Create and download the complete bilingual complaint report in the browser. */
export async function downloadReportPdf(complaint, result) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  let y = MARGIN;

  doc.setFillColor(23, 75, 53);
  doc.rect(0, 0, PAGE_WIDTH, 33, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(19);
  doc.setTextColor(255, 255, 255);
  doc.text('PuneSahayak', MARGIN, 15);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text('Civic complaint report', MARGIN, 23);
  if (result.reference) doc.text(`Reference: ${result.reference}`, PAGE_WIDTH - MARGIN, 23, { align: 'right' });
  y = 45;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.setTextColor(23, 75, 53);
  y = addWrappedText(doc, `Civic concern in ${(result.location || 'Pune').split(',')[0]}`, MARGIN, y, {
    fontSize: 15,
    lineHeight: 7,
    color: [23, 75, 53],
  });
  y += 3;

  y = addSection(doc, 'Complaint', complaint.text, y);
  y += 2;
  y = addSection(doc, 'Location', result.location || locationToText(complaint?.location) || 'Location not provided', y);
  y += 2;
  y = addSection(doc, 'Category', result.category, y);
  y += 2;
  y = addSection(doc, 'Urgency', result.urgency, y);
  y += 2;
  y = addSection(doc, 'Department', result.department, y);
  y += 2;

  if (complaint.image) {
    try {
      const dataUrl = await imageAsDataUrl(complaint.image);
      const dimensions = await imageDimensions(dataUrl);
      const imageType = (complaint.image.type || '').toLowerCase().includes('png') ? 'PNG' : 'JPEG';
      const maxWidth = CONTENT_WIDTH;
      const maxHeight = 72;
      const ratio = Math.min(maxWidth / dimensions.width, maxHeight / dimensions.height);
      const width = dimensions.width * ratio;
      const height = dimensions.height * ratio;
      y = addPageIfNeeded(doc, y, height + 16);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9);
      doc.setTextColor(23, 75, 53);
      doc.text('ATTACHED IMAGE', MARGIN, y);
      y += 5;
      doc.addImage(dataUrl, imageType, MARGIN, y, width, height);
      y += height + 6;
    } catch {
      y = addSection(doc, 'Attached image', 'The image was attached to the online complaint but could not be embedded in this PDF.', y);
      y += 2;
    }
  }

  y = addSection(doc, 'Issue summary', result.summary, y);
  y += 2;
  y = addSection(doc, 'Report (English)', result.englishReport, y);
  y += 2;
  y = addSection(doc, 'Report (Marathi)', result.marathiReport, y);
  y += 2;
  y = addSection(doc, 'Recommended actions', result.actions?.length ? result.actions.join(' • ') : result.report, y);
  y += 2;
  y = addSection(
    doc,
    'Disclaimer',
    result.disclaimer || 'This report is an AI-assisted draft for civic follow-up. Please verify the details and submit it through the appropriate official channel.',
    y,
  );

  doc.setFontSize(8);
  doc.setTextColor(109, 126, 117);
  doc.text('Generated by PuneSahayak · Keep this report for your records.', MARGIN, PAGE_HEIGHT - 10);
  const filenameLocation = (result.location || 'pune').split(',')[0].trim().replace(/[^a-z0-9]+/gi, '-').toLowerCase();
  doc.save(`punesahayak-${filenameLocation || 'civic-report'}.pdf`);
}
